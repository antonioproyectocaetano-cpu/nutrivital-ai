function computeItemNutrients(food, grams) {
  const g = Math.max(0, Number(grams) || 0);
  const ratio = g / 100;
  return {
    food_id: food.id,
    name: food.name,
    category: food.category,
    preparation_state: food.preparation_state,
    paired_food_id: food.paired_food_id || null,
    grams: Math.round(g),
    kcal: Math.round(food.kcal_per_100g * ratio),
    protein_g: Number((food.protein_per_100g * ratio).toFixed(1)),
    carbs_g: Number((food.carbs_per_100g * ratio).toFixed(1)),
    fat_g: Number((food.fat_per_100g * ratio).toFixed(1)),
    saturated_fat_g: Number(((food.saturated_fat_per_100g || 0) * ratio).toFixed(1)),
    fiber_g: Number(((food.fiber_per_100g || 0) * ratio).toFixed(1)),
    sugars_g: Number(((food.sugars_per_100g || 0) * ratio).toFixed(1)),
    free_sugars_g: Number(((food.free_sugars_per_100g || 0) * ratio).toFixed(1)),
    salt_g: Number(((food.salt_g_per_100g || 0) * ratio).toFixed(2)),
    fruit_veg_g: food.is_who_fruit_veg ? Math.round(g) : 0,
    is_who_legume: Boolean(food.is_who_legume),
    is_who_whole_grain: Boolean(food.is_who_whole_grain),
    source: food.source,
    source_code: food.source_code
  };
}

